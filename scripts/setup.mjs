// One command for a fresh checkout: start local Supabase, apply the migrations,
// write .env.local from the local stack and seed the demo academy.
//
// Run with: npm run setup

import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

function run(command) {
  console.log(`\n> ${command}`);
  execSync(command, { stdio: "inherit" });
}

function localStatus() {
  const output = execSync("npx supabase status -o env").toString();
  const values = {};

  for (const line of output.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)="?(.*?)"?$/);

    if (match) {
      values[match[1]] = match[2];
    }
  }

  return values;
}

/** Supabase sometimes needs a second attempt on a cold or busy Docker daemon. */
function startSupabase() {
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      run("npx supabase start");
      return;
    } catch (error) {
      if (attempt === 3) throw error;
      console.error(`\nSupabase did not start (attempt ${attempt}). Retrying.`);
    }
  }
}

async function waitForApi(url) {
  const deadline = Date.now() + 60_000;

  while (Date.now() < deadline) {
    try {
      const response = await fetch(`${url}/auth/v1/health`);
      if (response.ok) return;
    } catch {}

    await new Promise((resolve) => setTimeout(resolve, 1000));
  }

  throw new Error(`The local API at ${url} did not answer within a minute.`);
}

try {
  startSupabase();
} catch {
  console.error(
    "\nLocal Supabase did not start. Is Docker Desktop running? If the ports are\n" +
      "taken, run `npx supabase stop` and try again.\n",
  );
  process.exit(1);
}

await waitForApi(localStatus().API_URL);

run("npx supabase db reset");

const status = localStatus();

if (!status.API_URL || !status.PUBLISHABLE_KEY || !status.SECRET_KEY) {
  console.error(
    "\nThe local stack did not report an API URL and keys. Run `npx supabase status`.",
  );
  process.exit(1);
}

writeFileSync(
  ".env.local",
  [
    "# Generated by `npm run setup` for local development. Not committed.",
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
    `SUPABASE_SECRET_KEY=${status.SECRET_KEY}`,
    "",
    "# Demo account passwords, used by the seed.",
    `DEMO_DIRECTOR_PASSWORD=${process.env.DEMO_DIRECTOR_PASSWORD ?? "Demo1234!"}`,
    `DEMO_COACH_U16_PASSWORD=${process.env.DEMO_COACH_U16_PASSWORD ?? "Demo1234!"}`,
    `DEMO_COACH_U18_PASSWORD=${process.env.DEMO_COACH_U18_PASSWORD ?? "Demo1234!"}`,
    `DEMO_PLAYER_PASSWORD=${process.env.DEMO_PLAYER_PASSWORD ?? "Demo1234!"}`,
    "",
  ].join("\n"),
);

console.log("\nWrote .env.local from the local Supabase stack.");

run("node --env-file=.env.local supabase/seed/seed.mts");

console.log(
  "\nReady. Run `npm run dev` and sign in as director, omar.u16, layla.u18 or noura.u16.",
);
